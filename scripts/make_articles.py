#!/usr/bin/env python3
"""Generate the article models (model.config, model.sdf, texture PNG) from articles.yaml."""
import argparse
import random
from pathlib import Path

import numpy as np
import yaml
from PIL import Image, ImageDraw


def draw_texture(spec, size, seed):
    """Draw the texture of one article class and return a PIL image."""
    rng = random.Random(seed)
    img = Image.new('RGB', (size, size), spec['base'])
    draw = ImageDraw.Draw(img)
    for u0, v0, u1, v1, colour in spec.get('rects', []):
        draw.rectangle([u0 * size, v0 * size, u1 * size - 1, v1 * size - 1], fill=colour)
    badge = spec.get('badge')
    if badge:
        cx, cy = badge['center'][0] * size, badge['center'][1] * size
        r = badge['radius'] * size
        draw.ellipse([cx - r, cy - r, cx + r, cy + r], fill=badge['color'])
        dots = badge.get('dots')
        if dots:
            for _ in range(dots['n']):
                # Random point inside the badge (rejection sampling), small dot
                while True:
                    dx, dy = rng.uniform(-r, r), rng.uniform(-r, r)
                    if dx * dx + dy * dy < (0.85 * r) ** 2:
                        break
                d = 0.025 * size
                draw.ellipse([cx + dx - d, cy + dy - d, cx + dx + d, cy + dy + d], fill=dots['color'])
    # Pixel noise so the surface is not perfectly flat-coloured
    arr = np.asarray(img).astype(np.float32)
    nrng = np.random.default_rng(seed)
    arr += nrng.normal(0.0, spec.get('noise', 0.0), arr.shape)
    return Image.fromarray(np.clip(arr, 0, 255).astype(np.uint8))


def geometry_and_inertia(art):
    """SDF geometry element and the principal moments of inertia of a solid primitive."""
    m = art['mass']
    if art['shape'] == 'box':
        x, y, z = art['size']
        geom = f'<box><size>{x} {y} {z}</size></box>'
        ixx, iyy, izz = m / 12 * (y * y + z * z), m / 12 * (x * x + z * z), m / 12 * (x * x + y * y)
        return geom, (ixx, iyy, izz), z
    r, h = art['size']
    geom = f'<cylinder><radius>{r}</radius><length>{h}</length></cylinder>'
    ixx = m / 12 * (3 * r * r + h * h)
    return geom, (ixx, ixx, m * r * r / 2), h


def check_limits(art, limits):
    if art['shape'] == 'box':
        width, height = min(art['size'][:2]), art['size'][2]
    else:
        width, height = 2 * art['size'][0], art['size'][1]
    if width > limits['gripper_opening']:
        raise ValueError(f"{art['name']}: {width * 1000:.0f} mm does not fit the gripper "
                         f"({limits['gripper_opening'] * 1000:.0f} mm)")
    if height > limits['max_height']:
        raise ValueError(f"{art['name']}: height {height} m is above {limits['max_height']} m")


def model_sdf(art):
    name = art['name']
    geom, (ixx, iyy, izz), height = geometry_and_inertia(art)
    return f'''<?xml version="1.0"?>
<sdf version="1.8">
  <model name="{name}">
    <link name="link">
      <!-- The model origin is the centre of the base: the body is lifted by half its height -->
      <pose>0 0 {height / 2:.4f} 0 0 0</pose>
      <inertial>
        <mass>{art['mass']}</mass>
        <inertia>
          <ixx>{ixx:.6g}</ixx><iyy>{iyy:.6g}</iyy><izz>{izz:.6g}</izz>
          <ixy>0</ixy><ixz>0</ixz><iyz>0</iyz>
        </inertia>
      </inertial>
      <collision name="collision">
        <geometry>{geom}</geometry>
        <surface>
          <friction><ode><mu>1.0</mu><mu2>1.0</mu2></ode></friction>
        </surface>
      </collision>
      <visual name="visual">
        <geometry>{geom}</geometry>
        <material>
          <ambient>1 1 1 1</ambient>
          <diffuse>1 1 1 1</diffuse>
          <pbr>
            <metal>
              <albedo_map>model://{name}/materials/textures/{name}.png</albedo_map>
              <roughness>0.8</roughness>
              <metalness>0.0</metalness>
            </metal>
          </pbr>
        </material>
      </visual>
    </link>
  </model>
</sdf>
'''


def model_config(name):
    return f'''<?xml version="1.0"?>
<model>
  <name>{name}</name>
  <version>1.0</version>
  <sdf version="1.8">model.sdf</sdf>
  <description>Warehouse article generated by make_articles.py</description>
</model>
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--spec', required=True, help='articles.yaml')
    ap.add_argument('--out', required=True, help='models directory')
    args = ap.parse_args()

    spec = yaml.safe_load(Path(args.spec).read_text())
    size = spec['texture_size']
    out = Path(args.out)
    for i, art in enumerate(spec['articles']):
        check_limits(art, spec['limits'])
        folder = out / art['name']
        (folder / 'materials' / 'textures').mkdir(parents=True, exist_ok=True)
        (folder / 'model.config').write_text(model_config(art['name']))
        (folder / 'model.sdf').write_text(model_sdf(art))
        draw_texture(art['texture'], size, seed=i).save(folder / 'materials' / 'textures' / f"{art['name']}.png")
        print(f"{art['name']:14s} {art['shape']:8s} size {art['size']}  mass {art['mass']} kg")
    print(f"wrote {len(spec['articles'])} models in {out}")


if __name__ == '__main__':
    main()
